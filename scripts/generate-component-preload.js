#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_MAIN = path.join(ROOT, 'Component-preload.js');
const OUT_NS_DIR = path.join(ROOT, 'sap_ui5');
const OUT_NS = path.join(OUT_NS_DIR, 'Component-preload.js');

const DIRS = ['control','controller','facades','infra','manager','model','ports','service','util','view','i18n','localService'];
const EXTRA = ['Component.js','manifest.json','ui5-background-runtime.js'];
const EXTS = new Set(['.js', '.json', '.xml', '.properties']);

function walk(dir, out) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const st = fs.statSync(full);
    if (st.isDirectory()) {
      walk(full, out);
      continue;
    }
    const ext = path.extname(name);
    if (!EXTS.has(ext)) continue;
    out.push(full);
  }
}

function readText(file) {
  let txt = fs.readFileSync(file, 'utf8');
  if (txt.charCodeAt(0) === 0xFEFF) txt = txt.slice(1);
  return txt;
}

function toModulePath(abs) {
  const rel = path.relative(ROOT, abs).replace(/\\/g, '/');
  return `sap_ui5/${rel}`;
}

const files = [];
for (const d of DIRS) {
  const abs = path.join(ROOT, d);
  if (fs.existsSync(abs)) walk(abs, files);
}
for (const e of EXTRA) {
  const abs = path.join(ROOT, e);
  if (fs.existsSync(abs)) files.push(abs);
}
files.sort();

const modules = {};
for (const f of files) modules[toModulePath(f)] = readText(f);

const banner = '/* auto-generated by scripts/generate-component-preload.js */\n';
const preloadPayload = JSON.stringify(modules);
const body = `(function(){\n  var m = ${preloadPayload};\n  function apply(){\n    if (window.sap && sap.ui && sap.ui.require && sap.ui.require.preload) {\n      sap.ui.require.preload(m, "sap_ui5");\n      return true;\n    }\n    return false;\n  }\n  if (!apply()) {\n    window.__ui5PreloadQueue = window.__ui5PreloadQueue || [];\n    window.__ui5PreloadQueue.push([m, "sap_ui5"]);\n  }\n}());\n`;
fs.writeFileSync(OUT_MAIN, banner + body, 'utf8');

if (!fs.existsSync(OUT_NS_DIR)) fs.mkdirSync(OUT_NS_DIR, { recursive: true });
fs.writeFileSync(OUT_NS, `/* namespace proxy */\n(function(){\n  var s = document.createElement('script');\n  s.src = '../Component-preload.js';\n  document.head.appendChild(s);\n}());\n`, 'utf8');

console.log(`Generated preload with ${files.length} assets -> ${path.relative(ROOT, OUT_MAIN)}`);
